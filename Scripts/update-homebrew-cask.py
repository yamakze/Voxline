#!/usr/bin/env python3
"""Generate the Cask from a versioned Mac release archive."""
import argparse
import hashlib
import re
import plistlib
import zipfile
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("tag", help="Stable release tag, for example v1.0.0")
parser.add_argument("archive", type=Path, help="Downloaded Voxline-<version>.zip")
parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "Casks" / "voxline.rb")
args = parser.parse_args()
if not re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+", args.tag):
    parser.error("Homebrew distribution uses stable version tags")
version = args.tag[1:]
if args.archive.name != f"Voxline-{version}.zip":
    parser.error("Archive filename must match the release tag")
digest = hashlib.sha256()
with args.archive.open("rb") as file:
    for block in iter(lambda: file.read(1024 * 1024), b""):
        digest.update(block)
with zipfile.ZipFile(args.archive) as archive:
    metadata = plistlib.loads(archive.read("Voxline.app/Contents/Info.plist"))
auto_updates = "  auto_updates true\n\n" if metadata.get("SUPublicEDKey") and metadata.get("SUFeedURL") else ""
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text(f'''# Generated by Scripts/update-homebrew-cask.py from the release archive.
cask "voxline" do
  version "{version}"
  sha256 "{digest.hexdigest()}"

  url "https://github.com/yamakze/Voxline/releases/download/v#{{version}}/Voxline-#{{version}}.zip"
  name "Voxline"
  desc "Native subtitle transcription, translation, and proofreading"
  homepage "https://github.com/yamakze/Voxline"

  livecheck do
    url :url
    strategy :github_latest
  end

{auto_updates}  depends_on macos: :sequoia

  app "Voxline.app"
end
''')
print(f"Updated {args.output}: {version} · SHA-256 {digest.hexdigest()}")
